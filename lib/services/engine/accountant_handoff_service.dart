  static String _sanitizeForPdf(String text) {
    return text.replaceAll('•', '-').replaceAll(RegExp(r'[^\x00-\x7F]'), '');
  }

  static pw.Widget _th(String text) => pw.Padding(
        padding: const pw.EdgeInsets.symmetric(horizontal: 6, vertical: 5),
        child: pw.Text(_sanitizeForPdf(text),
            style: pw.TextStyle(fontSize: 9, fontWeight: pw.FontWeight.bold)),
      );

  static pw.TableRow _tr(
          String cat, String code, double rec, String pct, double claim) =>
      pw.TableRow(
        children: [
          _td(cat),
          _td(code),
          _td('\$${rec.toStringAsFixed(2)}'),
          _td(pct),
          _td('\$${claim.toStringAsFixed(2)}'),
        ],
      );

  static pw.Widget _td(String text, {bool isBold = false, PdfColor? color}) =>
      pw.Padding(
        padding: const pw.EdgeInsets.symmetric(horizontal: 6, vertical: 5),
        child: pw.Text(
          _sanitizeForPdf(text),
          style: pw.TextStyle(
            fontSize: 9,
            fontWeight: isBold ? pw.FontWeight.bold : pw.FontWeight.normal,
            color: color,
          ),
        ),
      );
}

/// Internal helper for categorizing and scaling logbook vehicle running costs vs direct items.
class _LogbookCategoryBreakdown {
  final double fuelTotal;
  final double repairsTotal;
  final double regoInsTotal;
  final double interestTotal;
  final double tollsParkingTotal;
  final double toolsMaterialsTotal;
  final double businessPercentage;

  const _LogbookCategoryBreakdown({
    required this.fuelTotal,
    required this.repairsTotal,
    required this.regoInsTotal,
    required this.interestTotal,
    required this.tollsParkingTotal,
    required this.toolsMaterialsTotal,
    required this.businessPercentage,
  });

  factory _LogbookCategoryBreakdown.from(
      List<VehicleExpense> expenses, double businessPercentage) {
    double fuel = 0.0;
    double repairs = 0.0;
    double regoIns = 0.0;
    double interest = 0.0;
    double tollsParking = 0.0;
    double toolsMaterials = 0.0;

    for (final e in expenses) {
      switch (e.category) {
        case ExpenseCategory.fuel:
          fuel += e.amount;
          break;
        case ExpenseCategory.maintenanceTyres:
          repairs += e.amount;
          break;
        case ExpenseCategory.rego:
        case ExpenseCategory.insurance:
          regoIns += e.amount;
          break;
        case ExpenseCategory.interest:
          interest += e.amount;
          break;
        case ExpenseCategory.tollsParking:
          tollsParking += e.amount;
          break;
        case ExpenseCategory.toolsMaterials:
        case ExpenseCategory.otherBusiness:
          toolsMaterials += e.amount;
          break;
      }
    }

    return _LogbookCategoryBreakdown(
      fuelTotal: fuel,
      repairsTotal: repairs,
      regoInsTotal: regoIns,
      interestTotal: interest,
      tollsParkingTotal: tollsParking,
      toolsMaterialsTotal: toolsMaterials,
      businessPercentage: businessPercentage,
    );
  }

  double get bizPct => businessPercentage / 100.0;
  double get fuelClaim => fuelTotal * bizPct;
  double get repairsClaim => repairsTotal * bizPct;
  double get regoInsClaim => regoInsTotal * bizPct;
  double get interestClaim => interestTotal * bizPct;
  double get totalRunning =>
      fuelTotal + repairsTotal + regoInsTotal + interestTotal;
  double get totalCarClaim =>
      fuelClaim +
      repairsClaim +
      regoInsClaim +
      interestClaim +
      tollsParkingTotal;
}
