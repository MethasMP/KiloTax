/// Deliverable package containing the exact 2 files for the accountant:
/// - Case 1 (CPK): [Summary_Declaration.pdf] + [Tax_Ledger.xlsx]
/// - Case 2 (Logbook): [Tax_Report.pdf] + [Tax_Data.xlsx]
class AccountantHandoffPackage {
  final Vehicle vehicle;
  final String financialYear;
  final TaxMethod taxMethod;
  final File pdfFile;
  final File dataFile; // XLSX Excel Workbook for both CPK and Logbook
  final double claimAmount;
  final double businessPercentage;
  final int totalTrips;
  final int totalExpenses;
  final int verifiedReceiptsCount;
  final int unverifiedReceiptsCount;
  final int unspecifiedTripsCount;
  final List<String> reviewIssues;
  final double? centsPerKmRate;

  const AccountantHandoffPackage({
    required this.vehicle,
    required this.financialYear,
    required this.taxMethod,
    required this.pdfFile,
    required this.dataFile,
    required this.claimAmount,
    required this.businessPercentage,
    required this.totalTrips,
    required this.totalExpenses,
    required this.verifiedReceiptsCount,
    required this.unverifiedReceiptsCount,
    required this.unspecifiedTripsCount,
    required this.reviewIssues,
    this.centsPerKmRate,
  });

  List<String> get attachmentPaths => [pdfFile.path, dataFile.path];

  String get emailSubject =>
      'FY$financialYear Vehicle Tax Substantiation - ${vehicle.regoPlate} (${taxMethod == TaxMethod.centsPerKm ? "Cents-per-KM" : "Logbook"})';

  String get emailBody {
    final buffer = StringBuffer();
    buffer.writeln('Hi Accountant,\n');
    buffer.writeln(
        'Please find attached the FY$financialYear vehicle tax documentation for ${vehicle.make} ${vehicle.model} (${vehicle.regoPlate}).\n');
    if (taxMethod == TaxMethod.centsPerKm) {
      final rate = centsPerKmRate ?? AppConstants.activeTaxRule.centsPerKmRate;
      final safeRate = (rate > 0) ? rate : AppConstants.activeTaxRule.centsPerKmRate;
      final safeDistance = safeRate > 0 ? (claimAmount / safeRate) : 0.0;
      buffer
          .writeln('TAX METHOD: Cents per Kilometre (ITAA 1997 Division 28-C)');
      buffer.writeln(
          '- Business Travel: ${Formatters.distance(safeDistance)}');
      buffer.writeln(
          '- Deductible Claim (Box D1 Code S): \$${claimAmount.toStringAsFixed(2)}');
      buffer.writeln('- Attached Files (2):');
      buffer.writeln(
          '  1. ${pdfFile.uri.pathSegments.last} (Summary Declaration)');
      buffer.writeln(
          '  2. ${dataFile.uri.pathSegments.last} (Excel Workbook: Summary & Trip Ledger)');
      buffer.writeln(
          '\nNote: Per Division 28-C, fuel and maintenance receipts are not required and are excluded.');
    } else {
      buffer.writeln(
          'TAX METHOD: Logbook Method (ITAA 1997 Subdivision 28-F & TR 97/11)');
      buffer.writeln(
          '- Representative Business Use: ${businessPercentage.toStringAsFixed(2)}%');
      buffer.writeln(
          '- Deductible Claim (Box D1 Code B): \$${claimAmount.toStringAsFixed(2)}');
      buffer.writeln(
          '- Evidence Status: $verifiedReceiptsCount of $totalExpenses expenses backed by digital tax invoices.');
      buffer.writeln('- Attached Files (2):');
      buffer.writeln(
          '  1. ${pdfFile.uri.pathSegments.last} (Master Tax Report PDF)');
      buffer.writeln(
          '  2. ${dataFile.uri.pathSegments.last} (3-Tab Excel Workbook: Summary, Trips, Expenses)');
      if (verifiedReceiptsCount > 0 && verifiedReceiptsCount == totalExpenses) {
        buffer.writeln(
            '\nAll expenses are cross-referenced with trip references and high-resolution cloud receipt URLs.');
      } else if (verifiedReceiptsCount > 0) {
        buffer.writeln(
            '\nVerified expenses are cross-referenced with trip references and high-resolution cloud receipt URLs.');
      } else {
        buffer.writeln(
            '\nExpense records are detailed in the companion workbook (receipts pending verification).');
      }
    }
    buffer.writeln('\nGenerated by KiloTax - Australian Tax Evidence OS.');
    return buffer.toString();
  }
}

/// Orchestrates generating the 2 exact, clean deliverable files for Australian Tax Agents:
/// - Case 1: CPK Deliverables (1 Summary PDF + 1 2-Tab XLSX)
/// - Case 2: Logbook Deliverables (1 Master Report PDF + 1 Multi-Tab XLSX)
class AccountantHandoffService {
  const AccountantHandoffService();

  Future<AccountantHandoffPackage> buildPackage({
    required Vehicle vehicle,
    required AtoTaxRule taxRule,
    required List<Trip> trips,
    required List<VehicleExpense> expenses,
    required Directory outputDirectory,
    String? taxpayerName,
    String? abn,
    ByteData? regularFont,
    ByteData? boldFont,
  }) async {
    final effectiveTaxpayerName =
        (taxpayerName != null && taxpayerName.trim().isNotEmpty)
            ? taxpayerName.trim()
            : 'Taxpayer';
    final effectiveAbn =
        (abn != null && abn.trim().isNotEmpty) ? abn.trim() : 'Not provided';

    final isCpk = vehicle.taxMethod == TaxMethod.centsPerKm;
    final fy = taxRule.financialYear;
    final rego = vehicle.regoPlate.isNotEmpty ? vehicle.regoPlate : 'NO_REGO';

    // Filter relevant records
    final relevantTrips = trips
        .where((t) => t.vehicleId == vehicle.id && !t.isDeleted)
        .toList()
      ..sort((a, b) => a.date.compareTo(b.date));

    final relevantExpenses = expenses
        .where((e) =>
            e.vehicleId == vehicle.id && e.deletedAt == null && !e.isVaultOnly)
        .toList()
      ..sort((a, b) => a.date.compareTo(b.date));

    // Calculate Vehicle Opening Odometer & Closing Odometer
    final openingOdometer = relevantTrips.isNotEmpty
        ? relevantTrips
            .map((t) => t.startOdometer)
            .reduce((a, b) => a < b ? a : b)
        : vehicle.initialOdometer;
    final closingOdometer = relevantTrips.isNotEmpty
        ? relevantTrips
            .map((t) => t.endOdometer)
            .reduce((a, b) => a > b ? a : b)
        : openingOdometer;

    final summary = TaxCalculatorService.evaluateSummary(
      trips: relevantTrips,
      expenses: relevantExpenses,
      taxRule: taxRule,
    );

    // Review metrics
    var unspecifiedTrips = 0;
    for (final t in relevantTrips) {
      if (t.isBusiness &&
          (t.purpose.trim().isEmpty ||
              t.purpose.trim() == '?' ||
              t.purpose.contains('[Unspecified'))) {
        unspecifiedTrips++;
      }
    }

    var verifiedReceipts = 0;
    var unverifiedReceipts = 0;
    for (final exp in relevantExpenses) {
      final isVer =
          exp.receiptAudit?.reviewStatus == ReceiptReviewStatus.confirmed ||
              exp.receiptAudit?.reviewStatus == ReceiptReviewStatus.verified;
      if (isVer) {
        verifiedReceipts++;
      } else {
        unverifiedReceipts++;
      }
    }

    final reviewIssues = <String>[];
    if (unspecifiedTrips > 0) {
      reviewIssues
          .add('$unspecifiedTrips business trips have unspecified purpose.');
    }
    if (!isCpk && unverifiedReceipts > 0) {
      reviewIssues.add(
          '$unverifiedReceipts expense receipts are pending review or unverified.');
    }

    if (isCpk) {
      // ═══════════════════════════════════════════════════════════════════════
      // CASE 1: CENTS PER KM (CPK) - Exactly 2 files
      // ═══════════════════════════════════════════════════════════════════════
      final pdfBytes = await PdfExportService.generateBoxD1SummaryPdf(
        vehicle: vehicle,
        trips: relevantTrips,
        summary: summary,
        taxRule: taxRule,
        taxpayerName: effectiveTaxpayerName,
        abn: effectiveAbn,
        openingOdometer: openingOdometer,
        closingOdometer: closingOdometer,
      );

      final pdfFileName = ExportFileNameHelper.buildFileName(
        method: 'CPK',
        fy: fy,
        taxpayerName: effectiveTaxpayerName,
        rego: rego,
        documentType: 'Summary_Declaration',
        extension: 'pdf',
      );
      final pdfFile = File('${outputDirectory.path}/$pdfFileName');
      await pdfFile.writeAsBytes(pdfBytes);

      final xlsxBytes = _generateCpkExcelWorkbook(
        vehicle: vehicle,
        trips: relevantTrips,
        summary: summary,
        taxRule: taxRule,
        taxpayerName: effectiveTaxpayerName,
        abn: effectiveAbn,
        openingOdometer: openingOdometer,
        closingOdometer: closingOdometer,
      );

      final xlsxFileName = ExportFileNameHelper.buildFileName(
        method: 'CPK',
        fy: fy,
        taxpayerName: effectiveTaxpayerName,
        rego: rego,
        documentType: 'Tax_Ledger',
        extension: 'xlsx',
      );
      final dataFile = File('${outputDirectory.path}/$xlsxFileName');
      await dataFile.writeAsBytes(xlsxBytes);

      return AccountantHandoffPackage(
        vehicle: vehicle,
        financialYear: fy,
        taxMethod: TaxMethod.centsPerKm,
        pdfFile: pdfFile,
        dataFile: dataFile,
        claimAmount: summary.centsPerKmClaim,
        businessPercentage: summary.businessPercentage,
        totalTrips: relevantTrips.length,
        totalExpenses: relevantExpenses.length,
        verifiedReceiptsCount: verifiedReceipts,
        unverifiedReceiptsCount: unverifiedReceipts,
        unspecifiedTripsCount: unspecifiedTrips,
        reviewIssues: reviewIssues,
        centsPerKmRate: taxRule.centsPerKmRate,
      );
    } else {
      // ═══════════════════════════════════════════════════════════════════════
      // CASE 2: LOGBOOK METHOD - Exactly 2 files (PDF + Multi-Tab XLSX)
      // ═══════════════════════════════════════════════════════════════════════

      // 1. Master Logbook Tax Report PDF
      final pdfBytes = await _generateLogbookMasterReportPdf(
        vehicle: vehicle,
        trips: relevantTrips,
        expenses: relevantExpenses,
        summary: summary,
        taxRule: taxRule,
        taxpayerName: effectiveTaxpayerName,
        abn: effectiveAbn,
        openingOdometer: openingOdometer,
        closingOdometer: closingOdometer,
        verifiedReceipts: verifiedReceipts,
        totalExpenses: relevantExpenses.length,
        regularFont: regularFont,
        boldFont: boldFont,
      );

      final pdfFileName = ExportFileNameHelper.buildFileName(
        method: 'Logbook',
        fy: fy,
        taxpayerName: effectiveTaxpayerName,
        rego: rego,
        documentType: 'Master_Tax_Report',
        extension: 'pdf',
      );
      final pdfFile = File('${outputDirectory.path}/$pdfFileName');
      await pdfFile.writeAsBytes(pdfBytes);

      // 2. 3-Tab Excel Workbook (.xlsx)
      final xlsxBytes = _generateLogbookExcelWorkbook(
        vehicle: vehicle,
        trips: relevantTrips,
        expenses: relevantExpenses,
        summary: summary,
        taxRule: taxRule,
        taxpayerName: effectiveTaxpayerName,
        abn: effectiveAbn,
        openingOdometer: openingOdometer,
        closingOdometer: closingOdometer,
        verifiedReceipts: verifiedReceipts,
      );

      final xlsxFileName = ExportFileNameHelper.buildFileName(
        method: 'Logbook',
        fy: fy,
        taxpayerName: effectiveTaxpayerName,
        rego: rego,
        documentType: 'Tax_Ledger',
        extension: 'xlsx',
      );
      final dataFile = File('${outputDirectory.path}/$xlsxFileName');
      await dataFile.writeAsBytes(xlsxBytes);

      final cat = _LogbookCategoryBreakdown.from(
          relevantExpenses, summary.businessPercentage);
      return AccountantHandoffPackage(
        vehicle: vehicle,
        financialYear: fy,
        taxMethod: TaxMethod.logbook,
        pdfFile: pdfFile,
        dataFile: dataFile,
        claimAmount: cat.totalCarClaim,
        businessPercentage: summary.businessPercentage,
        totalTrips: relevantTrips.length,
        totalExpenses: relevantExpenses.length,
        verifiedReceiptsCount: verifiedReceipts,
        unverifiedReceiptsCount: unverifiedReceipts,
        unspecifiedTripsCount: unspecifiedTrips,
        reviewIssues: reviewIssues,
      );
    }
  }

  /// Generates the 2-tab Excel Workbook (.xlsx) for Cents-per-KM (CPK) substantiation:
  /// - Tab 1: Tax Summary (Taxpayer / Client Name, ABN, Vehicle Rego, Financial Year, Prescribed Cents-per-km rate, Capped Kilometres, Box D1 Code S Deduction Amount, Opening Odometer, Closing Odometer)
  /// - Tab 2: CPK Trip Ledger (Standard 14-column schedule: Trip_ID, Trip_Date, Start_Time, Vehicle_Rego, Origin_Address, Destination_Address, Distance_KM, ATO_Purpose_Category, Business_Purpose_Detail, Bulky_Tools_Carried, Statutory_Rate, Uncapped_Trip_Value_AUD, Cumulative_KM_Year, Cap_Status)
  static Uint8List _generateCpkExcelWorkbook({
    required Vehicle vehicle,
    required List<Trip> trips,
    required TaxSummary summary,
    required AtoTaxRule taxRule,
    required String taxpayerName,
    required String abn,
    required double openingOdometer,
    required double closingOdometer,
  }) {
    final builder = OpenXmlWorkbookBuilder();
    final businessKm = summary.businessKm;
    final cappedKm = businessKm > taxRule.centsPerKmMaxKm
        ? taxRule.centsPerKmMaxKm
        : businessKm;
    final claimAmount = summary.centsPerKmClaim;

    // ── TAB 1: TAX SUMMARY ───────────────────────────────────────────────────
    final summarySheet = builder.addSheet('Tax Summary');
    summarySheet
        .addRow(['KILOTAX VEHICLE TAX SUBSTANTIATION - ATO SCHEDULE D1 (CPK)']);
    summarySheet.addRow(['Taxpayer / Client Name', taxpayerName]);
    summarySheet.addRow(['ABN', abn]);
    summarySheet.addRow(['Vehicle Rego', vehicle.regoPlate]);
    summarySheet
        .addRow(['Vehicle Description', '${vehicle.make} ${vehicle.model}']);
    summarySheet.addRow(['Financial Year', 'FY${taxRule.financialYear}']);
    summarySheet.addRow(
        ['Tax Method', 'Cents per Kilometre (ITAA 1997 Division 28-C)']);
    summarySheet
        .addRow(['Prescribed Cents-per-km rate', taxRule.centsPerKmRate]);
    summarySheet.addRow(['Total Logged Business Travel (KM)', businessKm]);
    summarySheet.addRow(['Capped Kilometres', cappedKm]);
    summarySheet.addRow(['Box D1 Code S Deduction Amount', claimAmount]);
    summarySheet.addRow(['Opening Odometer', openingOdometer]);
    summarySheet.addRow(['Closing Odometer', closingOdometer]);
    summarySheet.addRow([]);
    summarySheet.addRow(['STATUTORY RETENTION & COMPLIANCE']);
    summarySheet.addRow(
        ['Statutory Cap', '5,000 km per vehicle per year (ITAA 1997 s 28-25)']);
    summarySheet.addRow([
      'Statutory Retention',
      'Retain all records for 5 years per Subdivision 28-H / Section 900-165'
    ]);

    // ── TAB 2: CPK TRIP LEDGER ───────────────────────────────────────────────
    final ledgerSheet = builder.addSheet('CPK Trip Ledger');
    ledgerSheet.addRow([
      'Trip_ID',
      'Trip_Date',
      'Start_Time',
      'Vehicle_Rego',
      'Origin_Address',
      'Destination_Address',
      'Distance_KM',
      'ATO_Purpose_Category',
      'Business_Purpose_Detail',
      'Bulky_Tools_Carried',
      'Statutory_Rate',
      'Uncapped_Trip_Value_AUD',
      'Cumulative_KM_Year',
      'Cap_Status',
    ]);

    double cumulativeKm = 0.0;
    var index = 1;

    for (final t in trips) {
      if (!t.isBusiness) continue; // CPK only tracks claimable business trips
      cumulativeKm += t.businessDistanceKm;

      final tripId =
          'CPK-${t.date.year}${(t.date.month).toString().padLeft(2, "0")}${(t.date.day).toString().padLeft(2, "0")}-${index.toString().padLeft(3, "0")}';
      final dateStr = t.date.toIso8601String().split('T').first;
      final startTime =
          '${t.date.hour.toString().padLeft(2, "0")}:${t.date.minute.toString().padLeft(2, "0")}';
      final rego = vehicle.regoPlate;
      final origin =
          (t.originAddress != null && t.originAddress!.trim().isNotEmpty)
              ? t.originAddress!
              : '[Unspecified Origin]';
      final dest = (t.destinationAddress != null &&
              t.destinationAddress!.trim().isNotEmpty)
          ? t.destinationAddress!
          : '[Unspecified Destination]';
      final dist = t.businessDistanceKm;
      final purposeCat = _mapAtoPurposeCategory(t.purpose);
      final purposeDetail =
          t.purpose.trim().isNotEmpty ? t.purpose : '[Unspecified Purpose]';
      final carriesBulkyTools = _isBulkyToolsTrip(t.purpose)
          ? 'YES (Vogt 75 ATC 4073 / TR 95/34)'
          : 'NO';
      final rate = taxRule.centsPerKmRate;
      final uncappedTripValue = t.businessDistanceKm * taxRule.centsPerKmRate;
      final cumKm = cumulativeKm;
      final capStatus = cumulativeKm <= taxRule.centsPerKmMaxKm
          ? 'UNDER_5000_CAP'
          : 'CAPPED_EXCESS';

      ledgerSheet.addRow([
        tripId,
        dateStr,
        startTime,
        rego,
        origin,
        dest,
        dist,
        purposeCat,
        purposeDetail,
        carriesBulkyTools,
        rate,
        uncappedTripValue,
        cumKm,
        capStatus,
      ]);
      index++;
    }

    return builder.buildBytes();
  }

  static bool _isBulkyToolsTrip(String purpose) {
    final lower = purpose.toLowerCase();
    return lower.contains('tool') ||
        lower.contains('material') ||
        lower.contains('equipment') ||
        lower.contains('ladder') ||
        lower.contains('job') ||
        lower.contains('site') ||
        lower.contains('bunnings');
  }

  static String _mapAtoPurposeCategory(String purpose) {
    if (_isBulkyToolsTrip(purpose)) return 'BULKY_TOOLS_TRADE_DUTY';
    final lower = purpose.toLowerCase();
    if (lower.contains('suppl') ||
        lower.contains('bunning') ||
        lower.contains('material')) {
      return 'TRADE_SUPPLY_RUN';
    }
    if (lower.contains('client') || lower.contains('job')) {
      return 'CLIENT_SITE_VISIT';
    }
    if (lower.contains('site') || lower.contains('work')) {
      return 'INTER_WORKSITE_TRAVEL';
    }
    return 'BUSINESS_DUTY';
  }

  /// Generates the 3-tab Excel Workbook (.xlsx) for Logbook substantiation:
  /// - Tab 1: Tax Summary (Box D1 Code 401-406 Breakdown & Evidence Declaration)
  /// - Tab 2: Logbook Trips (16-column standard ATO continuous odometer schedule)
  /// - Tab 3: Expenses & Receipts (Cross-referenced with Trip IDs & Cloud URLs)
  static Uint8List _generateLogbookExcelWorkbook({
    required Vehicle vehicle,
    required List<Trip> trips,
    required List<VehicleExpense> expenses,
    required TaxSummary summary,
    required AtoTaxRule taxRule,
    required String taxpayerName,
    required String abn,
    required double openingOdometer,
    required double closingOdometer,
    required int verifiedReceipts,
  }) {
    final builder = OpenXmlWorkbookBuilder();
    final cat =
        _LogbookCategoryBreakdown.from(expenses, summary.businessPercentage);

    // ── TAB 1: SUMMARY ────────────────────────────────────────────────────────
    final summarySheet = builder.addSheet('Tax Summary');
    summarySheet
        .addRow(['KILOTAX VEHICLE TAX SUBSTANTIATION - ATO SCHEDULE D1']);
    summarySheet.addRow(['Taxpayer / Client Name', taxpayerName]);
    summarySheet.addRow(['ABN', abn]);
    summarySheet.addRow(
        ['Vehicle', '${vehicle.make} ${vehicle.model} (${vehicle.regoPlate})']);
    summarySheet.addRow(['Opening Odometer (KM)', openingOdometer]);
    summarySheet.addRow(['Closing Odometer (KM)', closingOdometer]);
    summarySheet.addRow(['Financial Year', 'FY${taxRule.financialYear}']);
    summarySheet
        .addRow(['Tax Method', 'Logbook Method (ITAA 1997 Subdivision 28-F)']);
    summarySheet
        .addRow(['Representative Business %', summary.businessPercentage]);
    summarySheet.addRow(['Total Distance (KM)', summary.totalKm]);
    summarySheet.addRow(['Business Distance (KM)', summary.businessKm]);
    summarySheet.addRow([]);

    summarySheet.addRow([
      'ATO Box D1 Deduction Schedule',
      'Category Code',
      'Total Expense (AUD)',
      'Deductible Claim (AUD)'
    ]);
    summarySheet.addRow(['Fuel & Oil', '401', cat.fuelTotal, cat.fuelClaim]);
    summarySheet.addRow([
      'Service, Repairs & Tyres',
      '402',
      cat.repairsTotal,
      cat.repairsClaim
    ]);
    summarySheet.addRow([
      'Registration & Insurance',
      '403',
      cat.regoInsTotal,
      cat.regoInsClaim
    ]);
    summarySheet.addRow([
      'Car Loan Interest / Lease',
      '404',
      cat.interestTotal,
      cat.interestClaim
    ]);
    summarySheet.addRow([
      'Work Tolls & Parking (100% Direct)',
      '406',
      cat.tollsParkingTotal,
      cat.tollsParkingTotal
    ]);
    summarySheet.addRow([]);
    summarySheet.addRow([
      'TOTAL DEDUCTION (Box D1 Code B)',
      '',
      cat.totalRunning + cat.tollsParkingTotal,
      cat.totalCarClaim
    ]);
    summarySheet.addRow([]);
    summarySheet.addRow(['TRADE MATERIALS SEPARATION (ITAA 1997 s 8-1)']);
    summarySheet.addRow([
      'Tools & Materials (Bunnings/Reece)',
      '100% Direct Trade Deduction',
      cat.toolsMaterialsTotal,
      cat.toolsMaterialsTotal
    ]);
    summarySheet.addRow([]);
    summarySheet.addRow(['EVIDENCE & SUBSTANTIATION DECLARATION']);
    summarySheet.addRow([
      'Verified Invoices',
      '$verifiedReceipts of ${expenses.length} expenses verified'
    ]);
    summarySheet.addRow([
      'Statutory Retention',
      'Retain all records for 5 years per Subdivision 28-H / Section 900-165'
    ]);

    // ── TAB 2: LOGBOOK TRIPS ──────────────────────────────────────────────────
    final tripsSheet = builder.addSheet('Logbook Trips');
    tripsSheet.addRow([
      'Trip_Number',
      'Trip_Date',
      'Start_Time',
      'Vehicle_Rego',
      'Odometer_Start_KM',
      'Odometer_End_KM',
      'Distance_KM',
      'Classification',
      'Origin',
      'Destination',
      'ATO_Business_Purpose',
      'Driver_Name',
      'Linked_Expense_IDs',
    ]);

    final tripsById = {for (final t in trips) t.id: t};
    var tripNum = 1;
    for (final trip in trips) {
      tripsSheet.addRow([
        tripNum++,
        trip.date.toIso8601String().substring(0, 10),
        '${trip.date.hour.toString().padLeft(2, "0")}:${trip.date.minute.toString().padLeft(2, "0")}',
        vehicle.regoPlate,
        trip.startOdometer,
        trip.endOdometer,
        trip.distanceKm,
        trip.isMixed ? 'MIXED' : trip.classification.name.toUpperCase(),
        trip.shareRoute
            ? (trip.originAddress ?? 'Origin')
            : '[Private Journey]',
        trip.shareRoute
            ? (trip.destinationAddress ?? 'Destination')
            : '[Private Journey]',
        trip.isBusiness ? trip.purpose : '[Private Journey]',
        'Primary Driver',
        trip.linkedExpenseIds.join('; '),
      ]);
    }

    // ── TAB 3: VEHICLE EXPENSES & RECEIPTS ────────────────────────────────────
    final expensesSheet = builder.addSheet('Expenses & Receipts');
    expensesSheet.addRow([
      'Expense_ID',
      'Date',
      'Category',
      'Merchant_Name',
      'Merchant_ABN',
      'Gross_Amount_AUD',
      'GST_Amount_AUD',
      'Net_Amount_AUD',
      'Business_Percent',
      'Deductible_Amount_AUD',
      'Linked_Trip_Ref',
      'Linked_Trip_Date',
      'Linked_Trip_Odometer_Range',
      'Linked_Trip_Route',
      'Receipt_Verification_Status',
      'Cloud_Receipt_URL',
    ]);

    for (final exp in expenses) {
      final linkedTrip =
          exp.linkedTripId != null ? tripsById[exp.linkedTripId] : null;
      final tripDate = linkedTrip != null
          ? linkedTrip.date.toIso8601String().substring(0, 10)
          : '';
      final tripOdoRange = linkedTrip != null
          ? '${linkedTrip.startOdometer.toStringAsFixed(0)} - ${linkedTrip.endOdometer.toStringAsFixed(0)} KM'
          : '';
      final tripRoute = linkedTrip != null
          ? '${linkedTrip.originAddress ?? "Origin"} -> ${linkedTrip.destinationAddress ?? "Destination"} (${linkedTrip.distanceKm.toStringAsFixed(1)} km)'
          : '';
      final cloudUrl = (exp.receiptPath != null && exp.receiptPath!.isNotEmpty)
          ? '${AppConstants.supabaseUrl}/storage/v1/object/public/${AppConstants.receiptStorageBucket}/${vehicle.id}/${exp.id}.webp'
          : '';

      final merchantName =
          exp.receiptAudit?.ocrMerchant ?? exp.notes ?? exp.category.name;
      final merchantAbn = exp.receiptAudit?.ocrAbn ?? '';
      final grossAmount = exp.amount;
      final gstAmount = exp.gstAmount ?? (exp.amount / 11.0);
      final netAmount = grossAmount - gstAmount;
      final deductibleAmount = exp.category.isDirectlyDeductibleByDefault
          ? exp.amount * (exp.businessPercentage / 100.0)
          : exp.amount * (summary.businessPercentage / 100.0);

      expensesSheet.addRow([
        exp.id,
        exp.date.toIso8601String().substring(0, 10),
        exp.category.displayName,
        merchantName,
        merchantAbn,
        grossAmount,
        gstAmount,
        netAmount,
        exp.businessPercentage,
        deductibleAmount,
        exp.linkedTripId ?? '',
        tripDate,
        tripOdoRange,
        tripRoute,
        exp.receiptAudit?.reviewStatus.name ?? 'unverified',
        cloudUrl,
      ]);
    }

    return builder.buildBytes();
  }

